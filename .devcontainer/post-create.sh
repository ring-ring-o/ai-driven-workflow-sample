#!/usr/bin/env bash
# =============================================================================
# コンテナ作成後のセットアップ。VS Code の postCreateCommand から呼ばれる。
# docker compose だけで使う人も同じものを叩けばよい（＝環境が分岐しない）:
#
#   docker compose exec dev bash .devcontainer/post-create.sh
#
# 何度実行しても安全（冪等）。sudo は使わない（外部通信遮断中でも動くように）。
# root が必要な初期化（ボリュームの所有権・通信遮断）は起動時の
# devcontainer-init が済ませている。
#
# 依存解決をイメージではなくここでやる理由:
#   - 焼き込むとイメージが太り、しかも lock を更新した瞬間に古くなる
#   - pnpm の store はワークスペース側にあるので、2 回目以降はほぼ待たない
# =============================================================================
set -euo pipefail

WS="${WORKSPACE_FOLDER:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
cd "${WS}"

step() { printf '\n\033[1;34m==>\033[0m %s\n' "$*" >&2; }

# -----------------------------------------------------------------------------
# 1. mise
# -----------------------------------------------------------------------------
# ツールチェーンはイメージに焼いてあるので、通常ここは一瞬で終わる。
# mise.toml / mise.lock を更新した直後だけ、差分のツールが入る。
step "mise: mise.toml / mise.lock との差分を解決"
mise trust --quiet "${WS}/mise.toml" 2>/dev/null || true
mise install --locked
mise reshim

# -----------------------------------------------------------------------------
# 2. 依存解決
# -----------------------------------------------------------------------------
# SKIP_DEPS=1 を渡せば飛ばせる（イメージだけ試したいときなど）。
if [ "${SKIP_DEPS:-0}" = "1" ]; then
  step "依存解決をスキップ (SKIP_DEPS=1)"
else
  step "依存解決（pnpm install --frozen-lockfile）"
  mise run deps
fi

# -----------------------------------------------------------------------------
# 3. バージョン定義の整合性
# -----------------------------------------------------------------------------
# ズレていても警告だけにして先へ進める。コンテナが作れなくなるほどの問題ではなく、
# 直すのはコミット前でよいため。`mise run check` は同じ検証で落ちる。
step "バージョン定義の整合性を検証"
if ! mise run pins:check; then
  echo "    → 'mise run pins:sync' で揃えてからコミットすること" >&2
fi

# -----------------------------------------------------------------------------
# 4. 確認
# -----------------------------------------------------------------------------
step "環境"
mise run doctor

cat >&2 <<'EOS'
  次にやること:
    mise tasks              タスク一覧
    mise run check          型検査 + lint + バージョン整合性
    claude                  Claude Code（初回はブラウザでログイン）
    egress-firewall status  外部通信遮断の状態（既定: off / docs/egress-firewall.md）

EOS
